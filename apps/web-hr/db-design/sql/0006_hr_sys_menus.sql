SELECT r.id, m.id, true, true, true, true, true, true
FROM public.hr_roles r, public.hr_menus m
WHERE r.code = 'HR_ADMIN' AND r.deleted_at IS NULL
  AND m.type = 'ITEM' AND m.deleted_at IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM public.hr_role_menus rm
    WHERE rm.role_id = r.id AND rm.menu_id = m.id AND rm.deleted_at IS NULL
  );

