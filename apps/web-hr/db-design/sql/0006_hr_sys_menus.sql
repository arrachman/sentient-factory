-- web-hr Fase 0 — Menu HR (additive, 0 DROP)
-- Live hr_* tables are NOT Prisma-managed; applied via psql (db execute).
-- hr_menus = catalog menu sidebar HR (mirror field ERP sys_menus, namespace hr_).
-- hr_role_menus = grant role→menu (mirror ERP adm_role_menus, style HR junction).
-- Sidebar web-hr dikonsumsi dari GET /api/hr/sys-menus/my-menus (hr-sys-menus module).
-- Tree: MODULE (3 grup) → ITEM (17 route). MODULE selalu dipertahankan renderer;
-- hanya ITEM yang difilter by hr_role_menus.can_view (non-privileged user).
-- path kanonik = tanpa prefix /app (shell menambah base /app saat render URL),
-- persis konvensi ERP sys_menus.path.
-- Conventions mirror existing hr_ tables: integer id, plain timestamp, audit
-- quartet, soft-delete, indexed (FKs not enforced — decoupled style).
-- Apply: docker exec sentient-postgres-core psql -U root -d sentient_factory -f <this>

CREATE TABLE IF NOT EXISTS public.hr_menus (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  code        text NOT NULL,
  title       text NOT NULL,
  path        text,                                   -- canonical route id (tanpa /app)
  icon        text,                                   -- lucide icon name
  type        text NOT NULL CHECK (type IN ('MODULE', 'GROUP', 'ITEM')),
  parent_id   integer,                                -- hr_menus.id (MODULE untuk ITEM)
  sort_order  integer NOT NULL DEFAULT 0,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamp without time zone NOT NULL DEFAULT now(),
  created_by  integer,
  updated_at  timestamp without time zone,
  updated_by  integer,
  deleted_at  timestamp without time zone,
  deleted_by  integer
);

CREATE UNIQUE INDEX IF NOT EXISTS hr_menus_code_key
  ON public.hr_menus (code) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS hr_menus_parent_idx ON public.hr_menus (parent_id);
CREATE INDEX IF NOT EXISTS hr_menus_active_idx ON public.hr_menus (is_active);

-- Grant junction (style = hr_user_roles: surrogate id + unique partial + audit
-- quartet + soft-delete). can_* flags mirror ERP adm_role_menus; hanya can_view
-- yang dipakai filter my-menus saat ini, sisanya tersedia untuk per-action RBAC.
CREATE TABLE IF NOT EXISTS public.hr_role_menus (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  role_id     integer NOT NULL,                       -- hr_roles.id
  menu_id     integer NOT NULL,                       -- hr_menus.id
  can_view    boolean NOT NULL DEFAULT false,
  can_create  boolean NOT NULL DEFAULT false,
  can_edit    boolean NOT NULL DEFAULT false,
  can_delete  boolean NOT NULL DEFAULT false,
  can_approve boolean NOT NULL DEFAULT false,
  can_print   boolean NOT NULL DEFAULT false,
  can_export  boolean NOT NULL DEFAULT false,
  can_import  boolean NOT NULL DEFAULT false,
  is_favorite boolean NOT NULL DEFAULT false,
  created_at  timestamp without time zone NOT NULL DEFAULT now(),
  created_by  integer,
  updated_at  timestamp without time zone,
  updated_by  integer,
  deleted_at  timestamp without time zone,
  deleted_by  integer
);

CREATE UNIQUE INDEX IF NOT EXISTS hr_role_menus_role_menu_key
  ON public.hr_role_menus (role_id, menu_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS hr_role_menus_role_idx ON public.hr_role_menus (role_id);
CREATE INDEX IF NOT EXISTS hr_role_menus_menu_idx ON public.hr_role_menus (menu_id);

